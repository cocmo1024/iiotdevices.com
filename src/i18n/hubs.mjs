export function hubAlternates(path) {
	// path like '' (home), 'devices/', 'tools/', 'protocols/'
	const clean = path.replace(/^\//, '');
	return [
		{ hreflang: 'en', href: `/${clean}` },
		...HUB_LOCALES.map((l) => ({ hreflang: l, href: `/${l}/${clean}` })),
		{ hreflang: 'x-default', href: `/${clean}` },
	];
}
